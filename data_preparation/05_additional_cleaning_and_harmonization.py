organism_original = combined["Organism"].astype("string")

organism_normalized = (
    organism_original
    .str.strip()
    .str.replace(
        r"\s+",
        " ",
        regex=True,
    )
    # Standardize terminal sp, sp., spp, or spp. as spp.
    # Matching is case-insensitive so SP., SPP., etc. are also standardized.
    .str.replace(
        r"\s+spp?\.?$",
        " spp.",
        regex=True,
        flags=re.IGNORECASE,
    )
)


# -----------------------------------------------------------------------------
# Apply explicit spelling and taxonomic harmonization rules
# -----------------------------------------------------------------------------

organism_clean = organism_normalized.replace(
    organism_mapping
)


# -----------------------------------------------------------------------------
# Classify the identification resolution
# -----------------------------------------------------------------------------
#
# This variable helps prevent genus-only records, species groups, and ambiguous
# identifications from being treated as confirmed individual species in later
# analyses.
#
# "Named taxon" does not automatically guarantee that the record is eligible
# for a species-specific analysis. It means that the label was not recognized
# as one of the explicitly lower-resolution categories below.
# -----------------------------------------------------------------------------

def classify_organism_identification(organism_name):
    if pd.isna(organism_name):
        return "Missing"

    name = str(organism_name).strip()
    name_casefold = name.casefold()

    if name_casefold == "coagulase-negative staphylococcus spp.":
        return "Phenotypic organism group"

    if "/" in name:
        return "Ambiguous multi-taxon identification"

    if (
        name_casefold.endswith(" group")
        or name_casefold.endswith(" complex")
        or " species group" in name_casefold
        or " species complex" in name_casefold
    ):
        return "Species group or complex"

    if re.search(
        r"\bspp\.$",
        name_casefold,
    ):
        return "Genus-level identification"

    return "Named taxon"


organism_identification_type = (
    organism_clean
    .map(classify_organism_identification)
    .astype("string")
)


