# =============================================================================
# AUDIT MIC SCIENTIFIC NOTATION AND FLOATING-POINT PRECISION ARTIFACTS
# =============================================================================
#
# Purpose:
# - Identify MIC values stored in scientific notation.
# - Distinguish ordinary scientific notation from unusually long
#   floating-point representations.
# - Quantify the frequency by source database and antibiotic.
# - Confirm whether the long representations are numerically equivalent
#   to their shorter decimal forms.
# - Identify any MIC values that cannot be parsed as a number with an
#   optional censoring operator.
#
# Important:
# - This section does not modify the combined database.
# - Original MIC values and censoring operators are retained unchanged.
# - No MIC measurement is rounded, replaced, or reclassified.
# =============================================================================

import re

import pandas as pd
from IPython.display import display


# -----------------------------------------------------------------------------
# Confirm that the required objects are available
# -----------------------------------------------------------------------------

if "expected_antibiotics" not in globals():
    raise NameError(
        "expected_antibiotics was not found. Run the antibiotic-column "
        "audit section before running this section."
    )

if not combined.index.is_unique:
    raise ValueError(
        "The combined DataFrame index is not unique. A unique index is "
        "required to create an unambiguous row-level MIC audit."
    )


# Preserve basic structural information to confirm that this audit does not
# modify the database.
rows_before_mic_precision_audit = len(combined)
columns_before_mic_precision_audit = combined.columns.copy()


# -----------------------------------------------------------------------------
# Identify expected MIC columns that are present
# -----------------------------------------------------------------------------

mic_columns = [
    antibiotic_name
    for antibiotic_name in expected_antibiotics
    if antibiotic_name in combined.columns
]


# -----------------------------------------------------------------------------
# Define valid MIC formatting patterns
# -----------------------------------------------------------------------------
#
# Accepted examples:
# 0.015
# 2
# .5
# <=0.03
# <= 0.03
# >16
# 2E-3
# 1.4999999999999999E-2
# -----------------------------------------------------------------------------

mic_value_pattern = re.compile(
    r"^(?P<operator><=|>=|<|>)?"
    r"\s*"
    r"(?P<number>"
    r"(?:\d+(?:\.\d*)?|\.\d+)"
    r"(?:[eE][+-]?\d+)?"
    r")$"
)


# Scientific notation containing a very long decimal mantissa is flagged
# as a possible floating-point representation artifact.
long_scientific_notation_pattern = re.compile(
    r"^(?:<=|>=|<|>)?"
    r"\s*"
    r"(?:\d+\.\d{10,}|\.\d{10,})"
    r"[eE][+-]?\d+$"
)


# -----------------------------------------------------------------------------
# Inspect every observed MIC value
# -----------------------------------------------------------------------------

scientific_notation_records = []
precision_artifact_records = []
unparseable_mic_records = []

total_observed_mic_values = 0


for mic_column in mic_columns:

    mic_values = (
        combined[mic_column]
        .astype("string")
        .str.strip()
    )

    # Treat empty strings as missing for the audit only.
    mic_values = mic_values.mask(
        mic_values.eq("")
    )

    total_observed_mic_values += int(
        mic_values.notna().sum()
    )

    for row_index, raw_mic_value in mic_values.dropna().items():

        raw_mic_value = str(raw_mic_value)

        mic_match = mic_value_pattern.fullmatch(
            raw_mic_value
        )

        # Record any value that cannot be interpreted as a numeric MIC
        # with an optional censoring operator.
        if mic_match is None:

            unparseable_record = {
                "DataFrame Index": row_index,
                "Antibiotic Name": mic_column,
                "Raw MIC Value": raw_mic_value,
            }

            if "Source Database" in combined.columns:
                unparseable_record["Source Database"] = (
                    combined.at[row_index, "Source Database"]
                )

            if "Isolate Id" in combined.columns:
                unparseable_record["Isolate Id"] = (
                    combined.at[row_index, "Isolate Id"]
                )

            unparseable_mic_records.append(
                unparseable_record
            )

            continue

        operator = mic_match.group("operator") or ""
        numeric_text = mic_match.group("number")

        # Continue only if the numeric component uses scientific notation.
        if not re.search(r"[eE]", numeric_text):
            continue

        numeric_value = float(numeric_text)

        # Create a concise representation for comparison only.
        # This does not replace the original database value.
        concise_numeric_text = format(
            numeric_value,
            ".15g",
        )

        concise_mic_display = (
            f"{operator}{concise_numeric_text}"
        )

        numeric_equivalence_confirmed = (
            float(numeric_text)
            == float(concise_numeric_text)
        )

        is_long_precision_artifact = bool(
            long_scientific_notation_pattern.fullmatch(
                raw_mic_value
            )
        )

        scientific_record = {
            "DataFrame Index": row_index,
            "Antibiotic Name": mic_column,
            "Raw MIC Value": raw_mic_value,
            "Operator": operator,
            "Parsed Numeric MIC": numeric_value,
            "Concise Numeric Representation": (
                concise_mic_display
            ),
            "Long Precision Artifact": (
                is_long_precision_artifact
            ),
            "Numeric Equivalence Confirmed": (
                numeric_equivalence_confirmed
            ),
        }

        if "Source Database" in combined.columns:
            scientific_record["Source Database"] = (
                combined.at[row_index, "Source Database"]
            )

        if "Isolate Id" in combined.columns:
            scientific_record["Isolate Id"] = (
                combined.at[row_index, "Isolate Id"]
            )

        scientific_notation_records.append(
            scientific_record
        )

        if is_long_precision_artifact:
            precision_artifact_records.append(
                scientific_record.copy()
            )


